"""Machine-learning pipeline (specs 21-22).

Phase 4 lands in small pieces, and all of them are in:

* :mod:`core.ml.dataset` - the training matrix: each stored feature row joined to the
  forward label of the *same* instant, with the label-derived columns structurally excluded
  from the feature matrix and every dropped row counted. Spec 4.3's data-accumulation gates
  live here too, as a pure function.
* :mod:`core.ml.walk_forward` - spec 22's purged walk-forward splitter: whole trading days
  in order, an embargo that must cover the longest label horizon, a final untouched holdout,
  a fold report carrying exact timestamps, and the frames of a fold
  (:func:`core.ml.walk_forward.fold_frames`) so the trainer cannot re-derive the guards.
* :mod:`core.ml.trainer` - LightGBM multiclass training with fixed seeds, plus the whole
  walk-forward run: train each fold, score it, refit one model on every row outside the
  holdout.
* :mod:`core.ml.baselines` - spec 21's reference points (always-up, always-range, random,
  regime-only), each fitted on the training fold so a comparison is out-of-sample on both
  sides.
* :mod:`core.ml.evaluation` - the probability metrics (log loss, Brier score, calibration
  curves, accuracy), the per-fold model-vs-baseline comparison, and spec 4.3's gate as a
  label ("PRELIMINARY" is a result, not an apology).
* :mod:`core.ml.predictor` - spec 21's ``predictor``: score a *stored* artefact (booster text
  plus metadata) by rebuilding the training feature order and the categorical vocabulary,
  so a backtest's probabilities come from the same matrix the model was fitted on.
* :mod:`core.ml.explainer` - spec 26's explainability: one prediction in plain structured
  form, built from configured blocks of the stored feature row plus the model's own class
  probabilities, with a ``NULL`` feature reported as unknown and a column the row does not
  carry refused rather than blanked.
* :mod:`core.ml.importance` - spec 27's feature importance: the model's own gain, a
  permutation measurement on a *named* sample with a confidence interval over repeats, and an
  optional SHAP attribution that says why it did not run when it cannot - all reported per
  spec 27's own list of sources, with every feature no source claims still visible.
"""

